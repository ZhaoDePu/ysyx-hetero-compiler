"""Emit the checked C11 RoPE image for the runtime's frozen-RIG/board driver."""

from hetero_compiler.c11_qwen_rope import make_rope_image
from hetero_compiler.gpu import Program, _EXIT


def make_residual_image():
    program = Program(None)
    entries = []
    for warp in range(4):
        entries.append(4 * len(program.words))
        program.li(15, warp * 16)
        program.jump("residual")
    program.label("residual")
    program.emit(0xCC3022F3)
    program.arithmetic(5, 5, 15)
    program.li(1, 896)  # hidden width
    program.li(4, 0x2000)  # right-hand scratch vector
    program.li(7, -(1 << 26))
    program.li(8, 1 << 26)
    program.label("add")
    program.addi(2, 5, 2, f3=1)
    program.arithmetic(3, 2, 4)
    program.load(6, 2, "int32")
    program.load(9, 3, "int32")
    program.arithmetic(6, 6, 9)
    program.branch(5, 6, 7, "upper")
    program.addi(6, 7, 0)
    program.label("upper")
    program.branch(5, 8, 6, "store")
    program.addi(6, 8, 0)
    program.label("store")
    program.store(6, 2, "int32")
    program.addi(5, 5, 64)
    program.branch(6, 5, 1, "add")
    program.emit(_EXIT)
    return program.image(), entries


def emit_kernel(name, words, entries):
    print(f"static const uint32_t {name}_words[] = {{")
    for first in range(0, len(words), 8):
        print("    " + ", ".join(f"0x{value:08x}u" for value in words[first:first + 8]) + ",")
    print("};")
    print(f"static const uint32_t {name}_pc[] = {{")
    print("    " + ", ".join(str(entry) for entry in entries) + ",")
    print("};")


def main():
    print("/* Generated by tools.c11b_emit_rope from the compiler's shared kernels. */")
    words, jobs = make_rope_image()
    emit_kernel("c11b_rope", words, [job["entry"] for job in jobs])
    words, entries = make_residual_image()
    emit_kernel("c12_residual", words, entries)


if __name__ == "__main__":
    main()
