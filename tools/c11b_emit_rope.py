"""Emit the checked C11 RoPE image for the runtime's frozen-RIG/board driver."""

from hetero_compiler.c11_qwen_rope import make_rope_image


def main():
    words, jobs = make_rope_image()
    print("/* Generated by tools.c11b_emit_rope from the compiler's shared kernel. */")
    print("static const uint32_t c11b_rope_words[] = {")
    for first in range(0, len(words), 8):
        print("    " + ", ".join(f"0x{value:08x}u" for value in words[first:first + 8]) + ",")
    print("};")
    print("static const uint32_t c11b_rope_pc[] = {")
    print("    " + ", ".join(str(job["entry"]) for job in jobs) + ",")
    print("};")


if __name__ == "__main__":
    main()
